import { mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import sharp from "sharp";

import { homeZentrySlides } from "../lib/home-zentry-slides.ts";

// These are obvious artificial images for private functional tests only.
// Never deploy, publish, or interpret them as photographic approval.
if (
  process.env.CI !== "true" ||
  process.env.HOMEPAGE_REVIEW_MODE !== "private" ||
  process.env.HOMEPAGE_PUBLIC_ZENTRY_HERO === "true"
) {
  throw new Error("Synthetic hero media may only be generated by private CI.");
}
const paths = new Set();
for (const slide of homeZentrySlides) {
  for (const [role, asset] of [["full", slide.image], ["preview", slide.preview]]) {
    if (!/^\/media\/home\/hero-drafts\/[a-z-]+(?:-preview)?\.webp$/.test(asset) || paths.has(asset)) {
      throw new Error("Unsafe or duplicated private CI media path.");
    }
    paths.add(asset);
    const width = role === "full" ? 1800 : 450;
    const height = role === "full" ? 1100 : 300;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
      <rect width="100%" height="100%" fill="#28425b"/>
      <path d="M0 0 L${width} ${height}" stroke="#c2d9e6" stroke-width="30"/>
      <text x="50%" y="48%" text-anchor="middle" fill="#ffffff" font-size="42"
        font-family="sans-serif">${slide.id.toUpperCase()} - SYNTHETIC CI</text>
      <text x="50%" y="57%" text-anchor="middle" fill="#ffffff" font-size="27"
        font-family="sans-serif">NOT A REAL PHOTOGRAPH</text>
    </svg>`;
    const destination = join(process.cwd(), "public", asset.slice(1));
    await mkdir(dirname(destination), { recursive: true });
    await sharp(Buffer.from(svg)).webp({ quality: 70 }).toFile(destination);
  }
}
if (paths.size !== 14) throw new Error("Expected fourteen synthetic fixtures.");
console.log("Generated 14 disposable test-only WebP fixtures in ignored private directory.");
